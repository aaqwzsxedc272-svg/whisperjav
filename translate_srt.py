def load_original_english():
    """Load original English SRT translations for cues that already had English."""
    try:
        with open("original_english_translations.json", "r", encoding="utf-8") as f:
            return json.load(f)
    except FileNotFoundError:
        return {}


def generate_srt(cues, output_path):
    original = load_original_english()
    with open(output_path, "w", encoding="utf-8") as f:
        for c in cues:
            jp = c["japanese"]
            cid = c["id"]
            # Priority: 1) my new translations, 2) original English, 3) Japanese fallback
            if cid in TRANSLATIONS:
                en = TRANSLATIONS[cid]
            elif str(cid) in original:
                en = original[str(cid)]
            else:
                en = jp
            f.write(f"{c['id']}\n")
            f.write(f"{c['start']} --> {c['end']}\n")
            f.write(f"{en}\n\n")

    print(f"Wrote {output_path}: {len(cues)} cues")
    new_translated = sum(1 for c in cues if c["id"] in TRANSLATIONS)
    orig_translated = sum(1 for c in cues if c["id"] not in TRANSLATIONS and str(c["id"]) in original)
    fallback = sum(1 for c in cues if c["id"] not in TRANSLATIONS and str(c["id"]) not in original)
    print(f"New translations: {new_translated}, Original English: {orig_translated}, Japanese fallback: {fallback}")


